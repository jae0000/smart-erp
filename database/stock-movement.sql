WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE IF NOT EXISTS STOCK_MOVEMENT (
    MOVEMENT_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER(10) NOT NULL REFERENCES PRODUCT (PRODUCT_ID),
    DIRECTION VARCHAR2(3 CHAR) NOT NULL CHECK (DIRECTION IN ('IN', 'OUT')),
    QUANTITY NUMBER(10,0) NOT NULL CHECK (QUANTITY > 0),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_STOCK_MOVEMENT_PRODUCT ON STOCK_MOVEMENT (PRODUCT_ID);
