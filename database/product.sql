WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE IF NOT EXISTS PRODUCT (
    PRODUCT_ID NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRODUCT_CODE VARCHAR2(30 CHAR) NOT NULL UNIQUE,
    PRODUCT_NAME VARCHAR2(100 CHAR) NOT NULL,
    PRICE NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (PRICE >= 0),
    STOCK_QTY NUMBER(10,0) DEFAULT 0 NOT NULL CHECK (STOCK_QTY >= 0),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

MERGE INTO PRODUCT p
USING (
    SELECT 'P001' code, UNISTR('\BB34\C120 \B9C8\C6B0\C2A4') name FROM dual
) s ON (p.product_code = s.code)
WHEN MATCHED THEN
    UPDATE SET p.product_name = s.name
    WHERE p.product_name = UNISTR('\FFFD\FFFD\FFFD\FFFD\FFFD\FFFD \FFFD\FFFD\FFFD\FFFD\FFFD\FFFD\FFFD\FFFD\FFFD')
WHEN NOT MATCHED THEN
    INSERT (product_code, product_name, price, stock_qty)
    VALUES (s.code, s.name, 25000, 12);
COMMIT;
SELECT product_id, product_name, price FROM product ORDER BY product_id;
